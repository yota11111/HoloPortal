export function canonicalTalentName(name) {
  const cleaned = name?.trim();
  if (!cleaned) return "";
  return talentAliases[cleaned] || cleaned;
}

function escapeRegExp(value) {
  return value.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

function includesTalentTerm(text, term) {
  const cleaned = term?.trim();
  if (!cleaned) return false;
  const haystack = text.toLowerCase();
  const needle = cleaned.toLowerCase();

  if (/^[a-z0-9 '&.-]+$/i.test(cleaned)) {
    const pattern = escapeRegExp(needle).replace(/\s+/g, "\\s+");
    return new RegExp(`(^|[^a-z0-9])${pattern}(?=$|[^a-z0-9])`, "i").test(text);
  }

  return haystack.includes(needle);
}

export function talentSearchTerms(names = []) {
  const terms = new Set();
  const canonicalNames = new Set();

  for (const name of names) {
    const cleaned = name?.trim();
    if (!cleaned) continue;
    terms.add(cleaned);
    const canonical = canonicalTalentName(cleaned);
    if (!canonical) continue;
    terms.add(canonical);
    canonicalNames.add(canonical);
  }

  for (const [alias, canonical] of Object.entries(talentAliases)) {
    if (canonicalNames.has(canonical)) {
      terms.add(alias);
      terms.add(canonical);
    }
  }

  return [...terms].filter(Boolean);
}

export function talentSearchTermsFromText(text = "") {
  const canonicalNames = new Set();

  for (const [alias, canonical] of Object.entries(talentAliases)) {
    if (includesTalentTerm(text, alias) || includesTalentTerm(text, canonical)) {
      canonicalNames.add(canonical);
    }
  }

  return talentSearchTerms([...canonicalNames]);
}
